/* POSIX entry point. The guest address space is mapped first (boot_memory,
 * see there for why it must precede the window). With RECOMP_FB_WINDOW set,
 * xbox_HostWindowMain then opens the framebuffer window on this (main) thread
 * and runs boot_and_run on a second one; otherwise it just calls it. */
int main(int argc, char **argv)
{
    if (argc > 1 && strcmp(argv[1], "--renderers") == 0)
        return list_renderers();           /* for the start-up menus */
#if defined(SSX3_HAVE_VULKAN)
    if (argc > 1 && strcmp(argv[1], "--list-displays") == 0)
        return ssx3_vk_list_displays();   /* for the start-up menus */
#else
    if (argc > 1 && strcmp(argv[1], "--list-displays") == 0)
        return 0;                          /* no monitor choice without the Vulkan window */
#endif

    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);

    printf("=== SSX 3 (Xbox) - Static Recompilation ===\n");

    install_posix_fault_handler();
    if (boot_memory() != 0)
        return 1;
#if defined(SSX3_HAVE_VULKAN)
    {
        /* The Vulkan renderer owns the window: opened here on the main thread,
         * pumped from the start (the guest runs on its own thread). */
        const char *renderer = getenv("SSX3_RENDERER");
        if (renderer && strcmp(renderer, "vulkan") == 0)
            return ssx3_vk_host_main(boot_and_run);
    }
#endif
    return xbox_HostWindowMain(boot_and_run);
}
#endif
